package dev.xavier.stein.gradle;

import org.gradle.api.GradleException;
import org.gradle.api.logging.Logger;
import org.gradle.api.logging.Logging;
import org.gradle.process.ExecOperations;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The stein-sdk.jar as seen from Gradle: where it lives, how it is downloaded and how it is run.
 *
 * <p>The plugin repeats nothing from the SDK: no mappings, no name translation, no checking. It
 * runs the jar (with the toolchain's Java 25) and reads what it prints — so "gradlew build" and
 * "java -jar stein-sdk.jar build" produce the same .steinmod.
 */
final class SdkTool {

    static final String MC_VERSION = "1.8.9";

    /**
     * Where stein-sdk.jar releases are downloaded from. Stein-Project/stein-sdk is the public
     * distribution repository (and the template's Maven repository lives on its "maven" branch); it
     * changes only together with the template's settings.gradle and the guide. Plugins published
     * before the move read x4vieer/stein-sdk, which is frozen with the versions already there.
     */
    private static final String RELEASES =
            "https://github.com/Stein-Project/stein-sdk/releases/download/v";

    private SdkTool() {}

    /**
     * The plugin's own version, which is the SDK version it uses if the project does not name
     * another.
     */
    static String pluginVersion() {
        // version.txt is generated by the plugin build (build.gradle); no fallback on purpose.
        try (InputStream in = SdkTool.class.getResourceAsStream("version.txt")) {
            if (in == null) {
                throw new GradleException("version.txt is missing from the Stein plugin jar");
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8).trim();
        } catch (IOException e) {
            throw new GradleException("could not read the Stein plugin version", e);
        }
    }

    /**
     * The stein-sdk.jar of the requested version, in the Gradle cache (&lt;gradle
     * home&gt;/caches/stein-sdk/&lt;version&gt;). Downloaded once; the file only enters the cache
     * whole (downloaded alongside and swapped in), so two simultaneous builds do not get in each
     * other's way.
     */
    static File download(File gradleHome, String version, boolean offline) {
        Path target = gradleHome.toPath().resolve("caches/stein-sdk/" + version + "/stein-sdk.jar");
        if (Files.isRegularFile(target)) {
            return target.toFile();
        }
        String url = RELEASES + version + "/stein-sdk.jar";
        if (offline) {
            throw new GradleException(
                    "Stein SDK "
                            + version
                            + " is not in the Gradle cache and Gradle is offline ("
                            + url
                            + ")");
        }
        try {
            Files.createDirectories(target.getParent());
            HttpClient http =
                    HttpClient.newBuilder().followRedirects(HttpClient.Redirect.NORMAL).build();
            HttpResponse<byte[]> r =
                    http.send(
                            HttpRequest.newBuilder(URI.create(url)).build(),
                            HttpResponse.BodyHandlers.ofByteArray());
            byte[] body = r.body();
            // A jar starts with "PK": an error page does not go into the cache.
            if (r.statusCode() != 200 || body.length < 4 || body[0] != 'P' || body[1] != 'K') {
                throw new GradleException(
                        "could not download Stein SDK "
                                + version
                                + " (HTTP "
                                + r.statusCode()
                                + "): "
                                + url);
            }
            Path tmp = Files.createTempFile(target.getParent(), "stein-sdk", ".part");
            Files.write(tmp, body);
            Files.move(
                    tmp,
                    target,
                    StandardCopyOption.REPLACE_EXISTING,
                    StandardCopyOption.ATOMIC_MOVE);
            return target.toFile();
        } catch (IOException e) {
            throw new GradleException("could not download Stein SDK " + version + ": " + url, e);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new GradleException("interrupted while downloading " + url, e);
        }
    }

    /** The SDK's working folder, as the SDK itself finds it: STEIN_SDK_HOME, or ~/.stein-sdk. */
    static File defaultHome() {
        String env = System.getenv("STEIN_SDK_HOME");
        return env != null && !env.isBlank()
                ? new File(env)
                : new File(System.getProperty("user.home"), ".stein-sdk");
    }

    /** The file the setup leaves last: with it, the game is already assembled. */
    static File setupDone(File home) {
        return new File(home, MC_VERSION + "/libraries.txt");
    }

    /** The usual .minecraft, the same one the SDK uses. */
    static File defaultMinecraft() {
        String os = System.getProperty("os.name", "").toLowerCase(Locale.ROOT);
        String user = System.getProperty("user.home");
        if (os.contains("win")) {
            String appdata = System.getenv("APPDATA");
            return Paths.get(appdata != null ? appdata : user, ".minecraft").toFile();
        }
        if (os.contains("mac")) {
            return Paths.get(user, "Library", "Application Support", "minecraft").toFile();
        }
        return Paths.get(user, ".minecraft").toFile();
    }

    /**
     * The name of the .steinmod, by the same rule as the SDK: the "name" (or the "id") without
     * spaces or symbols.
     */
    static String modFileName(File steinmodJson, String fallback) {
        if (steinmodJson == null || !steinmodJson.isFile()) {
            return fallback + ".steinmod";
        }
        String json;
        try {
            json = Files.readString(steinmodJson.toPath());
        } catch (IOException e) {
            return fallback + ".steinmod";
        }
        String name = field(json, "name");
        String id = field(json, "id");
        String base = (name.isEmpty() ? id : name).replaceAll("[^A-Za-z0-9._-]", "");
        return (base.isEmpty() ? fallback : base) + ".steinmod";
    }

    private static String field(String json, String key) {
        Matcher m =
                Pattern.compile("\"" + Pattern.quote(key) + "\"\\s*:\\s*\"([^\"]*)\"")
                        .matcher(json);
        return m.find() ? m.group(1) : "";
    }

    /**
     * Runs "java -jar stein-sdk.jar args..." and returns what it printed. What goes to stderr goes
     * to Gradle's error; what goes to stdout, with a {@code log}, also goes to the console.
     */
    static String run(
            ExecOperations exec, File java, File sdkJar, File home, List<String> args, Logger log) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ByteArrayOutputStream err = new ByteArrayOutputStream();
        List<String> cmd = new ArrayList<>(List.of("-jar", sdkJar.getAbsolutePath()));
        cmd.addAll(args);
        var result =
                exec.exec(
                        spec -> {
                            spec.setExecutable(java.getAbsolutePath());
                            spec.setArgs(cmd);
                            spec.environment("STEIN_SDK_HOME", home.getAbsolutePath());
                            spec.setStandardOutput(out);
                            spec.setErrorOutput(err);
                            spec.setIgnoreExitValue(true);
                        });
        String stdout = out.toString(StandardCharsets.UTF_8);
        String stderr = err.toString(StandardCharsets.UTF_8);
        if (log != null && !stdout.isBlank()) {
            // Indented lines are lists (the classpath jars at the end of the setup): only with
            // --info.
            stdout.lines()
                    .forEach(
                            l -> {
                                if (l.startsWith("  ")) {
                                    log.info(l);
                                } else {
                                    log.lifecycle(l);
                                }
                            });
        }
        if (result.getExitValue() != 0) {
            throw new GradleException(
                    "stein-sdk " + String.join(" ", args) + " failed:\n" + stderr.strip());
        }
        if (!stderr.isBlank()) {
            Logger warn = log != null ? log : Logging.getLogger(SdkTool.class);
            stderr.lines().forEach(warn::warn);
        }
        return stdout;
    }

    /** The arguments of "setup": with {@code --mc <dir>} when the .minecraft is given. */
    static List<String> setupArgs(File minecraftDir) {
        List<String> args = new ArrayList<>(List.of("setup"));
        if (minecraftDir != null) {
            args.add("--mc");
            args.add(minecraftDir.getAbsolutePath());
        }
        return args;
    }

    /**
     * The output lines that are jars that exist: what "classpath" prints (and none of the
     * messages).
     */
    static List<File> jars(String output) {
        List<File> out = new ArrayList<>();
        for (String line : output.split("\\R")) {
            String l = line.strip();
            if (l.endsWith(".jar") && new File(l).isFile()) {
                out.add(new File(l));
            }
        }
        return out;
    }
}
